/** One subtitle line, [startMs] until [endMs]. */
class Cue(val startMs: Long, val endMs: Long, val text: String)

/** A video's subtitle track as the 字幕 row lists it. */
class SubtitleTrack(val stream: SubtitlesStream) {
    val label: String = stream.displayLanguageName + if (stream.isAutoGenerated) "（自动）" else ""
}

internal object Subtitles {
    /** The tracks worth offering: one per language and kind, people's before the machine's. */
    fun tracks(streams: List<SubtitlesStream>): List<SubtitleTrack> =
        streams.filter { it.isUrl }
            .distinctBy { it.languageTag + it.isAutoGenerated }
            .sortedBy { it.isAutoGenerated }
            .map(::SubtitleTrack)

    /**
     * Loads a track as YouTube's srv1 transcript (`<text start dur>` lines, clean even for the
     * rolling auto captions, unlike their WebVTT) and parses it. Blocking: call off main.
     */
    fun load(track: SubtitleTrack): List<Cue> {
        val url = track.stream.content.replace(Regex("&fmt=[^&]*"), "") + "&fmt=srv1"
        val body = Yt.downloader.get(url).responseBody()
        val parser = Xml.newPullParser()
        parser.setInput(body.reader())
        val cues = ArrayList<Cue>()
        while (parser.next() != XmlPullParser.END_DOCUMENT) {
            if (parser.eventType != XmlPullParser.START_TAG || parser.name != "text") continue
            val start = parser.getAttributeValue(null, "start")?.toDoubleOrNull() ?: continue
            val dur = parser.getAttributeValue(null, "dur")?.toDoubleOrNull() ?: 0.0
            // The text is HTML-escaped once more inside the XML (&amp;#39;).
            val raw = parser.nextText()
            val text = Html.fromHtml(raw, Html.FROM_HTML_MODE_LEGACY).toString().trim()
            if (text.isNotEmpty()) cues += Cue((start * 1000).toLong(), ((start + dur) * 1000).toLong(), text)
        }
        return cues
    }
}

/**
 * The subtitle line at the bottom of the picture, on a scrim plate: the one thing ever drawn
 * on the picture, and only once the viewer turns a track on (off by default).
 */
@Composable
internal fun SubtitleOverlay(big: Boolean, modifier: Modifier = Modifier) {
    val cues = Player.cues
    if (cues.isEmpty()) return
    var position by remember { mutableLongStateOf(0L) }
    LaunchedEffect(cues) {
        while (true) {
            position = Player.exo.currentPosition
            delay(100)
        }
    }
    val cue = remember(cues, position) { cues.lastOrNull { it.startMs <= position }?.takeIf { position < it.endMs } }
    val fade = YoinMotion.fastEffectsSpec<Float>()
    Box(modifier.fillMaxSize().padding(horizontal = 24.dp, vertical = if (big) 24.dp else 12.dp), contentAlignment = Alignment.BottomCenter) {
        AnimatedContent(
            targetState = cue?.text,
            transitionSpec = { fadeIn(fade) togetherWith fadeOut(fade) },
            label = "subtitle",
        ) { text ->
            if (text != null) {
                Text(
                    text,
                    style = if (big) MaterialTheme.typography.titleLarge else MaterialTheme.typography.bodyLarge,
                    color = Color.White,
                    textAlign = TextAlign.Center,
                    modifier = Modifier
                        .background(Color.Black.copy(alpha = 0.62f), YoinShapeTokens.Medium)
                        .padding(horizontal = 10.dp, vertical = 4.dp),
                )
            }
        }
    }
}
